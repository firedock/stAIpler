import { CANONICAL_SECTION_ORDER } from '@staipler/core';
import type { BenchmarkReadyBundle, LayerType } from '@staipler/core';

const ALWAYS_LOADED: LayerType[] = [
  'identity',
  'goals',
  'context',
  'constraints',
  'policies',
  'style',
  'memory',
];

const OPTIONAL_APPENDED: LayerType[] = ['examples', 'tools', 'prompts', 'evals'];

function titleCase(layer: LayerType): string {
  return layer.charAt(0).toUpperCase() + layer.slice(1);
}

export interface RenderedClaudeMd {
  body: string;
  includedLayers: LayerType[];
  excludedLayers: LayerType[];
}

export interface RenderOptions {
  releaseId: string;
  bundleHash: string;
  adapterVersion: string;
  coreContractVersion: number;
}

/**
 * Render CLAUDE.md from a BenchmarkReadyBundle. Adapter must not reach into
 * analyzer or pipeline internals — the bundle section list is the contract.
 */
export function renderClaudeMd(
  input: BenchmarkReadyBundle,
  opts: RenderOptions,
): RenderedClaudeMd {
  const sections = new Map<LayerType, string>();
  for (const s of input.bundle.sections) sections.set(s.layer, s.content);

  const included: LayerType[] = [];
  const excluded: LayerType[] = [];
  const parts: string[] = [];

  parts.push('<!-- staipler:claude-code -->');
  parts.push(`<!-- release_id=${opts.releaseId} bundle_hash=${opts.bundleHash} adapter_version=${opts.adapterVersion} core_contract_version=${opts.coreContractVersion} -->`);
  parts.push('<!-- This file is generated by @staipler/adapter-claude-code. Do not edit by hand. -->');
  parts.push('');

  const writeLayer = (layer: LayerType) => {
    const content = sections.get(layer);
    if (!content || content.trim().length === 0) {
      excluded.push(layer);
      return;
    }
    included.push(layer);
    parts.push(`## ${titleCase(layer)}`);
    parts.push('');
    parts.push(content.trim());
    parts.push('');
  };

  for (const layer of CANONICAL_SECTION_ORDER) {
    if (ALWAYS_LOADED.includes(layer)) writeLayer(layer);
  }

  const skillsSection = sections.get('skills');
  if (skillsSection && skillsSection.trim().length > 0) {
    parts.push('## Skills (on-demand)');
    parts.push('');
    parts.push('Procedural skills for this project are available under `.claude/skills/`. Claude Code will load them on demand.');
    parts.push('');
  }

  for (const layer of CANONICAL_SECTION_ORDER) {
    if (OPTIONAL_APPENDED.includes(layer)) writeLayer(layer);
  }

  parts.push('<!-- /staipler:claude-code -->');
  parts.push('');

  return {
    body: parts.join('\n'),
    includedLayers: included,
    excludedLayers: excluded,
  };
}
